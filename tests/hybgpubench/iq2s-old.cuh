static __device__ __forceinline__ float vec_dot_iq2_s_q8_1_old(
    const void * __restrict__ vbq, const block_q8_1 * __restrict__ bq8_1, const int & kbx, const int & iqs) {

    const block_iq2_s * bq2 = (const block_iq2_s *) vbq + kbx;

    const int       qs_packed = get_int_b2(bq2->qs, iqs/2);
    const uint8_t * qs        = (const uint8_t *) &qs_packed;

    const int qh = bq2->qh[iqs/2];

    const int       signs_packed_32 = get_int_b2(bq2->qs, QK_K/32 + iqs/2);
    const uint8_t * signs_packed_8  = (const uint8_t *) &signs_packed_32;

    const int ls0 = bq2->scales[iqs/2] & 0x0F;
    const int ls1 = bq2->scales[iqs/2] >> 4;

    int sumi0 = 0;
    int sumi1 = 0;
#pragma unroll
    for (int l0 = 0; l0 < 8; l0 += 2) {
        const int * grid_pos = (const int *)(iq2s_grid + (qs[l0/2] | ((qh << (8-l0)) & 0x300)));

        // a byte 0xff per negative value: bit k of the 4 sign bits to bit 0 of byte k (the shifted copies do not
        // overlap), then times 0xff; negated bytewise as (g ^ m) + 1, no carry out of a byte (grid values <= 43)
        const uint32_t sb = signs_packed_8[l0/2];
        const uint32_t signs0 = (((sb & 0x0F) * 0x00204081u) & 0x01010101u) * 0xFFu;
        const uint32_t signs1 = (((sb >>   4) * 0x00204081u) & 0x01010101u) * 0xFFu;

        const int grid_l = (grid_pos[0] ^ signs0) + (signs0 & 0x01010101u);
        const int grid_h = (grid_pos[1] ^ signs1) + (signs1 & 0x01010101u);

        const int u0 = get_int_b4(bq8_1[iqs/2].qs, l0 + 0);
        const int u1 = get_int_b4(bq8_1[iqs/2].qs, l0 + 1);

        if (l0 < 4) {
            sumi0 = ggml_cuda_dp4a(grid_l, u0, sumi0);
            sumi0 = ggml_cuda_dp4a(grid_h, u1, sumi0);
        } else {
            sumi1 = ggml_cuda_dp4a(grid_l, u0, sumi1);
            sumi1 = ggml_cuda_dp4a(grid_h, u1, sumi1);
        }
    }
    const int sumi = (sumi0*ls0 + sumi1*ls1 + (sumi0 + sumi1)/2)/4;

    const float d = __half2float(bq2->d) * __low2float(bq8_1[iqs/2].ds);
    return d * sumi;
}
